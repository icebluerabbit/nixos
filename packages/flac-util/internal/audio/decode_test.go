func TestDecodeNonFLAC(t *testing.T) {
	path := filepath.Join(t.TempDir(), "not-audio.flac")
	if err := os.WriteFile(path, []byte("still not a FLAC stream"), 0o600); err != nil {
		t.Fatalf("WriteFile() error = %v", err)
	}
	if _, err := Decode(t.Context(), path, DecodeOptions{}); err == nil {
		t.Fatal("Decode() on a non-FLAC file succeeded, want error")
	}
}

func TestDecodeRejectsUnmeasurableFormat(t *testing.T) {
	// A spectrum configuration the measurement package refuses must surface as
	// an error rather than a panic.
	opts := DecodeOptions{Measure: measure.Options{Spectrum: measure.SpectrumOptions{FFTSize: 3}}}
	if _, err := Decode(t.Context(), fixture(t, fixtureSine16), opts); err == nil {
		t.Fatal("Decode() with an invalid spectrum configuration succeeded, want error")
	}
}

func TestDecodeBufferSizeDoesNotChangeResults(t *testing.T) {
	base := decodeFixture(t, fixtureSine16, DecodeOptions{
		Measure: measure.Options{SkipSpectrum: true},
	})
	tiny := decodeFixture(t, fixtureSine16, DecodeOptions{
		Measure:    measure.Options{SkipSpectrum: true},
		BufferSize: 512,
	})

	if base.Results.Fingerprint != tiny.Results.Fingerprint {
		t.Errorf("buffer size changed the checksum: %+v then %+v",
			base.Results.Fingerprint, tiny.Results.Fingerprint)
	}
}
