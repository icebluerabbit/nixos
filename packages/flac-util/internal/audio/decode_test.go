func decodeFixture(t *testing.T, name string, opts DecodeOptions) DecodeResult {
	t.Helper()
	got, err := Decode(t.Context(), fixture(t, name), opts)
	if err != nil {
		t.Fatalf("Decode(%s) error = %v", name, err)
	}
	return got
}

// TestDecodeReproducesStoredChecksum is the load-bearing test for the decoding
// path. The expected values come from metaflac, so agreement proves that this
// program decodes the audio the reference implementation does, and that the
// checksum is assembled with the byte order and interleaving FLAC specifies.
func TestDecodeReproducesStoredChecksum(t *testing.T) {
	for _, name := range []string{fixtureSine16, fixtureHires24, fixturePadded24, fixtureSilence} {
		t.Run(name, func(t *testing.T) {
			got := decodeFixture(t, name, DecodeOptions{Measure: measure.Options{SkipSpectrum: true}})

			if got.Results.Fingerprint.MD5 != got.StreamInfo.MD5 {
				t.Errorf("recomputed MD5 = %q, stored MD5 = %q",
					got.Results.Fingerprint.MD5, got.StreamInfo.MD5)
			}
			if got.Results.Fingerprint.Samples != got.StreamInfo.TotalSamples {
				t.Errorf("decoded %d samples, header declares %d",
					got.Results.Fingerprint.Samples, got.StreamInfo.TotalSamples)
			}
			if got.Frames == 0 {
				t.Error("Frames = 0, want at least one")
			}
		})
	}
}

// TestDecodeFindsPaddedResolution is the measurement the high-resolution half
// of the tool rests on: a file declaring 24 bits while carrying 16 bits of
// detail must be reported as such.
func TestDecodeFindsPaddedResolution(t *testing.T) {
	tests := []struct {
		file          string
		declared      int
		wantEffective int
		wantUnused    int
	}{
		{fixtureSine16, 16, 16, 0},
		{fixturePadded24, 24, 16, 8},
	}
	for _, tt := range tests {
		t.Run(tt.file, func(t *testing.T) {
			got := decodeFixture(t, tt.file, DecodeOptions{Measure: measure.Options{SkipSpectrum: true}})
			bits := got.Results.Bits

			if bits.DeclaredBits != tt.declared {
				t.Errorf("DeclaredBits = %d, want %d", bits.DeclaredBits, tt.declared)
			}
			if bits.EffectiveBits != tt.wantEffective {
				t.Errorf("EffectiveBits = %d, want %d", bits.EffectiveBits, tt.wantEffective)
			}
			if got := bits.Channels[0].UnusedLowBits; got != tt.wantUnused {
				t.Errorf("UnusedLowBits = %d, want %d", got, tt.wantUnused)
			}
		})
	}
}

func TestDecodeSilence(t *testing.T) {
	got := decodeFixture(t, fixtureSilence, DecodeOptions{Measure: measure.Options{SkipSpectrum: true}})

	if !got.Results.Silence.AllSilent {
		t.Error("AllSilent = false, want true")
	}
	if !math.IsInf(got.Results.Levels.Channels[0].PeakDBFS, -1) {
		t.Errorf("PeakDBFS = %v, want -Inf", got.Results.Levels.Channels[0].PeakDBFS)
	}
	for i, ch := range got.Results.Bits.Channels {
		if !ch.AllZero {
			t.Errorf("channel %d AllZero = false, want true", i)
		}
	}
}

// TestDecodeLocatesToneInSpectrum checks the whole chain end to end: a file
// containing a known tone must show its peak at the matching frequency.
func TestDecodeLocatesToneInSpectrum(t *testing.T) {
	const toneHz = 1000

	opts := DecodeOptions{Measure: measure.Options{Spectrum: measure.DefaultSpectrumOptions()}}
	got := decodeFixture(t, fixtureSine16, opts)

	grid := got.Results.Spectrum
	if grid == nil {
		t.Fatal("Spectrum is nil, want a grid")
	}
	if grid.Columns() == 0 {
		t.Fatal("grid has no columns")
	}

	peak := 0
	column := grid.Power[0]
	for k, p := range column {
		if p > column[peak] {
			peak = k
		}
	}

	// The tone need only land within one bin of where it belongs.
	if got := grid.BinFrequency(peak); math.Abs(got-toneHz) > grid.BinHz() {
		t.Errorf("spectral peak at %v Hz, want approximately %v Hz", got, toneHz)
	}
}

