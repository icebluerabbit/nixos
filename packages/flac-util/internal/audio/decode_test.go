func TestDecodeStereoOfDuplicatedChannels(t *testing.T) {
	// The fixtures are generated by copying one channel to both, so the two
	// must be reported as identical.
	got := decodeFixture(t, fixtureSine16, DecodeOptions{Measure: measure.Options{SkipSpectrum: true}})
	stereo := got.Results.Stereo

	if !stereo.Applicable {
		t.Fatal("Applicable = false, want true")
	}
	if stereo.IdenticalSamples != stereo.TotalSamples {
		t.Errorf("IdenticalSamples = %d of %d, want all of them",
			stereo.IdenticalSamples, stereo.TotalSamples)
	}
	if math.Abs(stereo.Correlation-1) > 1e-9 {
		t.Errorf("Correlation = %v, want 1", stereo.Correlation)
	}
}

// TestDecodeSkipsLeadingID3 covers a file carrying a prepended ID3v2 block.
// The decoder steps over one on its own, so decoding must succeed and produce
// the same audio as the untagged original.
func TestDecodeSkipsLeadingID3(t *testing.T) {
	opts := DecodeOptions{Measure: measure.Options{SkipSpectrum: true}}

	got := decodeFixture(t, fixtureID3, opts)
	if got.Results.Fingerprint.MD5 != got.StreamInfo.MD5 {
		t.Errorf("recomputed MD5 = %q, stored MD5 = %q",
			got.Results.Fingerprint.MD5, got.StreamInfo.MD5)
	}

	// The fixture is the plain one with a tag block glued on the front, so the
	// audio must be identical.
	plain := decodeFixture(t, fixtureSine16, opts)
	if got.Results.Fingerprint != plain.Results.Fingerprint {
		t.Errorf("prefixed file decoded to %+v, the plain one to %+v",
			got.Results.Fingerprint, plain.Results.Fingerprint)
	}
}

func TestDecodeHonoursCancellation(t *testing.T) {
	ctx, cancel := context.WithCancel(t.Context())
	cancel()

	_, err := Decode(ctx, fixture(t, fixtureSine16), DecodeOptions{
		Measure: measure.Options{SkipSpectrum: true},
	})
	if err == nil {
		t.Fatal("Decode() with a cancelled context succeeded, want error")
	}
	if !errors.Is(err, context.Canceled) {
		t.Errorf("Decode() error = %v, want a cancellation", err)
	}
}

