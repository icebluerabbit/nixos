package render

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"strings"

	"homelab/app"
	"homelab/topology/internal/graph"
	"homelab/topology/internal/infra"
)

// The views this tool can render.
const (
	// ViewPhysical is what is plugged into what, derived from the
	// port-profile join.
	ViewPhysical = "physical"
	// ViewLogical is the server's own VLANs, bridges and containers past the
	// trunk.
	ViewLogical = "logical"
)

// Default flag values.
const (
	// DefaultView is the cabling diagram, which is the one a reader wants
	// first.
	DefaultView = ViewPhysical
	// DefaultHost is the only host running containers, so it is the only
	// interesting subject for the logical view.
	DefaultHost = "server"
	// DefaultMarker names the BEGIN/END pair in --into. A page holding both
	// views passes a marker per view instead.
	DefaultMarker = "topology"
)

// banner marks the region as machine-written wherever it lands.
const banner = "<!-- Generated by `just topology`. Do not edit. -->\n\n"

// Config is what the tool takes on the command line.
type Config struct {
	// View selects the diagram: physical or logical.
	View string `json:"view"`
	// Host is the host the logical view describes.
	Host string `json:"host"`
	// Into is a markdown file to splice into; empty writes to stdout.
	Into string `json:"into"`
	// Marker is the name of the BEGIN/END marker pair in Into.
	Marker string `json:"marker"`
}

// Defaults returns the configuration a caller that passes no flags gets.
func Defaults() Config {
	return Config{
		View:   DefaultView,
		Host:   DefaultHost,
		Marker: DefaultMarker,
	}
}

// ErrNoInput reports an empty stdin, which is almost always a forgotten pipe.
var ErrNoInput = errors.New("no input: pipe `nix eval .#nixosConfigurations.<host>.config.infra --json`")

// ErrUnknownView reports a --view nobody renders.
var ErrUnknownView = errors.New("unknown view")

// ErrNoMarkers reports an --into file with nowhere to put the diagram.
var ErrNoMarkers = errors.New("no marker block")

// Run reads the registries on stdin and renders one view.
func Run(env *app.Env, cfg Config, stdin io.Reader) error {
	raw, err := io.ReadAll(stdin)
	if err != nil {
		return fmt.Errorf("read stdin: %w", err)
	}
	if len(raw) == 0 {
		return ErrNoInput
	}

	var in infra.Input
	if err := json.Unmarshal(raw, &in); err != nil {
		return fmt.Errorf("parse json: %w", err)
	}

	var out string
	switch cfg.View {
	case ViewPhysical:
		out = Mermaid(graph.BuildPhysical(in.Infra))
	case ViewLogical:
		out = Logical(graph.BuildLogical(in, cfg.Host))
	default:
		return fmt.Errorf("%w %q", ErrUnknownView, cfg.View)
	}

	// No heading. The file being spliced into owns its own structure —
	// emitting one here guessed at a level and nested wrong.
	doc := banner + out

	if cfg.Into == "" {
		_, err := io.WriteString(env.Stdout, doc)
		return err
	}
	return splice(cfg.Into, cfg.Marker, doc)
}

// splice replaces the region between `<!-- BEGIN <marker> -->` and
// `<!-- END <marker> -->` in place.
//
// GitHub renders static markdown — there is no include, no transclusion, no
// template pass — so a README that shows generated content has to physically
// contain it. Markers are the usual workaround: they keep the generated region
// addressable so regenerating touches nothing a human wrote.
//
// Missing markers are an error rather than an append: silently bolting content
// onto the end of someone's README is worse than refusing.
func splice(path, marker, content string) error {
	raw, err := os.ReadFile(path) //nolint:gosec // the path is the caller's choice
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}

	begin := fmt.Sprintf("<!-- BEGIN %s -->", marker)
	end := fmt.Sprintf("<!-- END %s -->", marker)

	i := strings.Index(string(raw), begin)
	j := strings.Index(string(raw), end)
	if i < 0 || j < 0 || j < i {
		return fmt.Errorf("%w: %s has no %s / %s block; add one where the diagram should go",
			ErrNoMarkers, path, begin, end)
	}

	// Fenced off from prettier, which treefmt runs over markdown. Prettier
	// pads table columns to align them; this tool emits them unpadded.
	// Without the fence the two rewrite each other forever — `nix fmt`
	// reformats, `just topology` un-formats, and the pre-commit hook runs the
	// formatter.
	updated := string(raw[:i]) + begin +
		"\n\n<!-- prettier-ignore-start -->\n\n" + content +
		"\n<!-- prettier-ignore-end -->\n\n" + string(raw[j:])
	//nolint:gosec // a README is world-readable by design
	return os.WriteFile(path, []byte(updated), 0o644)
}
