package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"
)

const usage = `topology — render network diagrams from the infra registries.

Reads ` + "`config.infra`" + ` as JSON on stdin:

  nix eval .#nixosConfigurations.server.config.infra --json | topology > docs/topology.md

Views:
  physical   what is plugged into what, derived from the port-profile join
  logical    the server's own VLANs, bridges and containers past the trunk
`

func main() {
	view := flag.String("view", "physical", "which diagram to render")
	host := flag.String("host", "server", "host the logical view describes")
	into := flag.String("into", "", "markdown file to splice into; stdout if unset")
	marker := flag.String("marker", "topology", "name of the BEGIN/END marker pair in --into")
	flag.Usage = func() {
		fmt.Fprint(os.Stderr, usage)
		flag.PrintDefaults()
	}
	flag.Parse()

	raw, err := io.ReadAll(os.Stdin)
	if err != nil {
		fatal("read stdin: %v", err)
	}
	if len(raw) == 0 {
		fatal("no input: pipe `nix eval .#nixosConfigurations.<host>.config.infra --json`")
	}

	var in Input
	if err := json.Unmarshal(raw, &in); err != nil {
		fatal("parse json: %v", err)
	}

	var out string
	switch *view {
	case "physical":
		out = RenderMermaid(BuildPhysical(in.Infra))
	case "logical":
		out = RenderLogical(BuildLogical(in, *host))
	default:
		fatal("unknown view %q", *view)
	}

	// No heading. The file being spliced into owns its own structure — emitting
	// one here guessed at a level and nested wrong.
	var doc strings.Builder
	doc.WriteString("<!-- Generated by `just topology`. Do not edit. -->\n\n")
	doc.WriteString(out)

	if *into == "" {
		fmt.Print(doc.String())
		return
	}
	if err := splice(*into, *marker, doc.String()); err != nil {
		fatal("%v", err)
	}
}

// splice replaces the region between `<!-- BEGIN <marker> -->` and
// `<!-- END <marker> -->` in place.
//
// GitHub renders static markdown — there is no include, no transclusion, no
// template pass — so a README that shows generated content has to physically
// contain it. Markers are the usual workaround: they keep the generated region
// addressable so regenerating touches nothing a human wrote.
//
// Missing markers are an error rather than an append: silently bolting content
// onto the end of someone's README is worse than refusing.
func splice(path, marker, content string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}

	begin := fmt.Sprintf("<!-- BEGIN %s -->", marker)
	end := fmt.Sprintf("<!-- END %s -->", marker)

	i := strings.Index(string(raw), begin)
	j := strings.Index(string(raw), end)
	if i < 0 || j < 0 || j < i {
		return fmt.Errorf("%s has no %s / %s block; add one where the diagram should go", path, begin, end)
	}

	// Fenced off from prettier, which treefmt runs over markdown. Prettier pads
	// table columns to align them; this tool emits them unpadded. Without the
	// fence the two rewrite each other forever — `nix fmt` reformats, `just
	// topology` un-formats, and the pre-commit hook runs the formatter.
	updated := string(raw[:i]) + begin +
		"\n\n<!-- prettier-ignore-start -->\n\n" + content +
		"\n<!-- prettier-ignore-end -->\n\n" + string(raw[j:])
	return os.WriteFile(path, []byte(updated), 0o644)
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "topology: "+format+"\n", args...)
	os.Exit(1)
}
